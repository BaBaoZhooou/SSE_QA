function flattenYamlObject(obj, out = {}) {
  for (const [key, value] of Object.entries(obj || {})) {
    if (value && typeof value === "object" && !Array.isArray(value)) {
      flattenYamlObject(value, out);
    } else if (value !== null && value !== undefined && value !== "") {
      out[key] = String(value);
    }
  }
  return out;
}

export function renderSystemEnv(cfg = loadUserConfig()) {
  const yamlText = renderSystemYaml(cfg);
  const parsed = {};
  let section = parsed;
  const stack = [parsed];
  for (const line of yamlText.split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith("#")) continue;
    const indent = line.match(/^ */)?.[0].length ?? 0;
    const content = line.trim();
    const colon = content.indexOf(":");
    if (colon <= 0) continue;
    const key = content.slice(0, colon).trim();
    const rest = content.slice(colon + 1).trim();
    while (stack.length > 1 && indent <= stack.length - 1) stack.pop();
    section = stack[stack.length - 1];
    if (!rest) {
      const child = {};
      section[key] = child;
      stack.push(child);
      continue;
    }
    section[key] = rest;
  }
  const flat = flattenYamlObject(parsed);
  const lines = Object.entries(flat)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `${k}=${v}`);
  return `${lines.join("\n")}\n`;
}

export function renderDockerEnv(cfg = loadUserConfig()) {
  const secrets = loadSecretsEnv();
  const fastPath = expandPath(cfg.chroma?.fastqa?.vector_db_path || "");
  const fastMdPath = expandPath(cfg.chroma?.fastqa?.vector_db_md_path || `${fastPath}_md`);
  const thinkPath = expandPath(cfg.chroma?.thinking?.persist_dir || "");
  const ports = cfg.ports || {};
  const lines = [
    `SSE_QA_VERSION=${process.env.SSE_QA_VERSION || "0.2.0"}`,
    `FASTQA_PORT=${ports.fastqa || 18018}`,
    `HIGHTHINKINGQA_PORT=${ports.thinking || 18019}`,
    `REDIS_PORT=${ports.redis || 16380}`,
    `CHROMA_FASTQA_HOST_PATH=${fastPath}`,
    `CHROMA_FASTQA_MD_HOST_PATH=${fastMdPath}`,
    `CHROMA_THINKING_HOST_PATH=${thinkPath}`,
    `LLM_API_KEY=${secrets.LLM_API_KEY || secrets.DASHSCOPE_API_KEY || ""}`,
    `INTENT_MODEL_API_KEY=${secrets.INTENT_MODEL_API_KEY || secrets.LLM_API_KEY || ""}`,
    `HIGHTHINKINGQA_EMBEDDING_API_KEY=${secrets.HIGHTHINKINGQA_EMBEDDING_API_KEY || secrets.LLM_API_KEY || ""}`,
    `EMBEDDING_API_KEY=${secrets.EMBEDDING_API_KEY || secrets.LLM_API_KEY || ""}`,
    `NEO4J_PASSWORD=${secrets.NEO4J_PASSWORD || secrets.FASTQA_NEO4J_PASSWORD || ""}`,
    `FASTQA_NEO4J_PASSWORD=${secrets.FASTQA_NEO4J_PASSWORD || secrets.NEO4J_PASSWORD || ""}`,
    `FASTQA_NEO4J_URL=${cfg.neo4j?.url || "bolt://host.docker.internal:7698"}`,
    `SSE_QA_CONFIG_HOME=${expandPath("~/.sse-qa")}`,
  ];
  return `${lines.join("\n")}\n`;
}

export function renderAllConfigs(cfg = loadUserConfig()) {
  ensureRuntimeDir();
  writeText(systemYamlPath(), renderSystemYaml(cfg));
  writeText(systemEnvPath(), renderSystemEnv(cfg));
  writeText(dockerEnvPath(), renderDockerEnv(cfg));
  return {
    systemYaml: systemYamlPath(),
    systemEnv: systemEnvPath(),
    dockerEnv: dockerEnvPath(),
  };
}
