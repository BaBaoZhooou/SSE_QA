function graphEnabled(cfg) {
  const neo = cfg.neo4j || {};
  if (neo.enabled === false) return false;
  if (neo.schema === "off") return false;
  return Boolean(neo.enabled);
}

function graphSchema(cfg) {
  const schema = String(cfg.neo4j?.schema || "sse").trim();
  return schema === "off" ? "sse" : schema;
}

export function validateUserConfig(cfg = loadUserConfig()) {
  const errors = [];
  const fastPath = expandPath(cfg.chroma?.fastqa?.vector_db_path || "");
  const thinkPath = expandPath(cfg.chroma?.thinking?.persist_dir || "");
  if (!fastPath) errors.push("chroma.fastqa.vector_db_path is required");
  else if (!existsSync(fastPath)) errors.push(`chroma.fastqa path not found: ${fastPath}`);
  if (!thinkPath) errors.push("chroma.thinking.persist_dir is required");
  else if (!existsSync(thinkPath)) errors.push(`chroma.thinking path not found: ${thinkPath}`);
  const secrets = loadSecretsEnv();
  if (!secrets.LLM_API_KEY && !secrets.DASHSCOPE_API_KEY) {
    errors.push("secrets.env missing LLM_API_KEY");
  }
  if (graphEnabled(cfg) && !secrets.NEO4J_PASSWORD && !secrets.FASTQA_NEO4J_PASSWORD) {
    errors.push("secrets.env missing NEO4J_PASSWORD (neo4j enabled)");
  }
  return { success: errors.length === 0, errors };
}

